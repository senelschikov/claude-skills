import { describe, expect, test } from 'claude-code/testing'

import { BUCKETS, bump, cell, coerce, coerceStored, dim, fresh, inject, latency, merge, mergeStored, percentile, renderStats, tokens, view } from './metrics'
import type { Session } from './metrics'

const one = (s: Session, sessions = 1) => renderStats(view({ t: 0, by: { [dim('p', 'main')]: s } }, { t: 0, by: {} }, sessions))

describe('metrics', () => {
  test('bump, inject and latency buckets', () => {
    const s = fresh(5)
    bump(s, 'edit', 'deny')
    bump(s, 'edit', 'prevLines', 7)
    inject(s, 'deny', 2000)
    latency(s, 'edit', 0.4)
    latency(s, 'edit', 7)
    latency(s, 'edit', 99999)
    expect(s.m.edit.deny).toBe(1)
    expect(s.m.edit.prevLines).toBe(7)
    expect(s.inj.deny).toBe(2000)
    expect(s.m.edit.lat[0]).toBe(1)
    expect(s.m.edit.lat[3]).toBe(1)
    expect(s.m.edit.lat[BUCKETS.length]).toBe(1)
  })
  test('percentile reads the bucket edge', () => {
    const lat = new Array<number>(BUCKETS.length + 1).fill(0)
    expect(Number.isNaN(percentile(lat, 50))).toBe(true)
    lat[2] = 8
    lat[5] = 1
    lat[12] = 1
    expect(percentile(lat, 50)).toBe(5)
    expect(percentile(lat, 90)).toBe(50)
    expect(percentile(lat, 100)).toBe(Infinity)
  })
  test('merge sums fields and histograms, keeps the newest t', () => {
    const a = fresh(1)
    const b = fresh(9)
    bump(a, 'post', 'checks', 2)
    bump(b, 'post', 'checks', 3)
    latency(a, 'commit', 3)
    latency(b, 'commit', 3)
    inject(a, 'short', 10)
    const m = merge([a, b])
    expect(m.t).toBe(9)
    expect(m.m.post.checks).toBe(5)
    expect(m.m.commit.lat[2]).toBe(2)
    expect(m.inj.short).toBe(10)
  })
  test('coerce fills an old or broken value', () => {
    expect(coerce(undefined).m.edit.calls).toBe(0)
    const c = coerce({ t: 3, m: { edit: { deny: 2, lat: [1] } }, inj: { deny: 8 } })
    expect(c.t).toBe(3)
    expect(c.m.edit.deny).toBe(2)
    expect(c.m.edit.lat).toHaveLength(BUCKETS.length + 1)
    expect(c.m.post.calls).toBe(0)
    expect(c.inj.deny).toBe(8)
    expect(c.inj.stats).toBe(0)
  })
  test('render shows every mode, the abuse flag and the estimate labels', () => {
    const s = fresh(1)
    bump(s, 'edit', 'deny', 4)
    bump(s, 'edit', 'first', 4)
    bump(s, 'edit', 'resub', 2)
    bump(s, 'edit', 'fixed', 1)
    bump(s, 'edit', 'prevChars', 800)
    bump(s, 'edit', 'prevLines', 12)
    inject(s, 'deny', 400)
    latency(s, 'edit', 12)
    const text = one(s, 2)
    expect(text).toMatch(/^comment-guard stats, 2 session\(s\)/)
    for (const mode of ['edit', 'heredoc', 'commit', 'post']) expect(text).toMatch(new RegExp(`^${mode} `, 'm'))
    expect(text).toMatch(/50%!/)
    expect(text).toMatch(/\bopen\b/)
    expect(text).toMatch(/ESTIMATE/)
    expect(text).toMatch(/savings, ESTIMATE: ~200 tokens from 12 comment lines/)
    expect(text).toMatch(/cost: ~100 tokens/)
    expect(text).toMatch(/net: ~100 tokens, rewrite estimated as retry; break-even after 1 future read/)
    expect(tokens(5)).toBe(2)
  })
  test('edit row carries deny - fixed - resub as open', () => {
    const s = fresh(1)
    bump(s, 'heredoc', 'deny', 5)
    bump(s, 'heredoc', 'fixed', 1)
    bump(s, 'heredoc', 'resub', 1)
    const row = one(s).split('\n').find(l => l.startsWith('heredoc'))
    expect(row?.split(/\s+/)[10]).toBe('3')
  })
  test('dimensions: origin split, project ranking, filter, current session', () => {
    const a = { t: 1, by: {} }
    bump(cell(a, dim('gitops', 'main')), 'edit', 'checks', 5)
    bump(cell(a, dim('gitops', 'sub')), 'edit', 'checks', 2)
    bump(cell(a, dim('helm', 'main')), 'post', 'checks', 9)
    bump(cell(a, dim('helm', 'main')), 'post', 'deny', 1)
    const b = coerceStored({ t: 2, m: { edit: { checks: 1 } } })
    const all = mergeStored([a, b])
    const v = view(all, b, 2)
    expect(v.projects.map(([n]) => n)).toEqual(['helm', 'gitops', '?'])
    expect(v.main.m.edit.checks).toBe(6)
    expect(v.sub.m.edit.checks).toBe(2)
    const text = renderStats(v)
    expect(text).toMatch(/^main agent: checks 15, deny 1, fixed 0, net ~0 tokens$/m)
    expect(text).toMatch(/^subagents: checks 2,/m)
    expect(text).toMatch(/^project helm: checks 9, deny 1,/m)
    expect(text).toMatch(/^current session: checks 1,/m)
    const f = renderStats(view(all, a, 2, 'gitops'))
    expect(f).toMatch(/^comment-guard stats for project gitops/)
    expect(f).not.toMatch(/^project /m)
    expect(f).toMatch(/^current session: checks 7,/m)
    expect(f.split('\n').find(l => l.startsWith('edit'))?.split(/\s+/)[2]).toBe('7')
  })
  test('old flat values land under project ?, main', () => {
    expect(Object.keys(coerceStored({ t: 1, m: { post: { calls: 2 } } }).by)).toEqual([dim('?', 'main')])
    expect(coerceStored(undefined).by).toEqual({})
  })
})
